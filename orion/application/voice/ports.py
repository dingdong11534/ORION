"""Application-layer ports for offline speech-to-text, text-to-speech, and audio I/O."""

from pathlib import Path
from typing import Protocol


class SpeechToTextPort(Protocol):
    """Offline speech-to-text engine port."""

    def is_model_available(self) -> bool: ...

    def model_path(self) -> Path: ...

    def transcribe(self, wav_path: Path) -> str: ...

    def unload(self) -> None: ...


class TextToSpeechPort(Protocol):
    """Offline text-to-speech engine port."""

    def is_model_available(self) -> bool: ...

    def model_path(self) -> Path: ...

    def synthesize_to_wav(self, text: str, output_wav: Path) -> Path: ...

    def unload(self) -> None: ...


class AudioInputPort(Protocol):
    """Local microphone capture port."""

    def is_available(self) -> bool: ...

    def backend_name(self) -> str: ...

    def start_recording(self, output_wav: Path, device: str = "default") -> None: ...

    def stop_recording(self) -> Path: ...

    def cancel_recording(self) -> None: ...


class AudioOutputPort(Protocol):
    """Local audio playback port."""

    def play_wav(self, wav_path: Path) -> None: ...

    def stop_playback(self) -> None: ...

    def is_playing(self) -> bool: ...
